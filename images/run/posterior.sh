#!/bin/bash
# Online class posterior during unconditional generation: agreement between the posterior's argmax
# and a pretrained ViT classifier, as a function of time, plus example trajectories.
#
#   bash run/posterior.sh
#
# Results: logs/Results/<run>/agreement_vs_time_*.csv, figures: logs/Figures/<run>/classifier_accuracy/

# Every setting below can also be overridden from the environment, e.g. NOISE=masking bash run/posterior.sh
NOISE=${NOISE:-uniform}                                 # uniform | masking
RUN_NAME=MNIST_dit_xs_bs512_${NOISE}_ema
UNCOND_RUN_NAME=MNIST_dit_xs_bs512_${NOISE}_ema_uncond

# noise.scheduler_type is the noise schedule used for *sampling* (cosine, 128 steps).
# With guid_scale=0 the images are generated by the separately trained unconditional model
# (UNCOND_RUN_NAME), which is also the baseline of every posterior update, as for the NOT gate.
# sampling.normalize_by_unmask_count only affects masking: it rescales each posterior update by the
# number of pixels unmasked in that step.
python -m scripts.posterior_classifier_agreement \
    sampling.run_name=$RUN_NAME \
    sampling.uncond_run_name=$UNCOND_RUN_NAME \
    noise.type=$NOISE \
    noise.scheduler_type=cosine \
    sampling.num_steps=128 \
    sampling.guid_scale=0 \
    sampling.num_samples=2048 \
    sampling.normalize_by_unmask_count=true
